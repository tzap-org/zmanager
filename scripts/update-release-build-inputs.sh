#!/usr/bin/env bash
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
lock="$root/release-build-inputs.lock"
mode="${1:---check}"
[[ $# -le 1 && ( "$mode" == --check || "$mode" == --write ) ]] || { echo "Usage: scripts/update-release-build-inputs.sh [--check|--write]" >&2; exit 2; }
[[ -f "$lock" ]] || { echo "Missing release input inventory: $lock" >&2; exit 1; }
parent="${ZMANAGER_SIBLING_PARENT_DIR:-$(dirname "$root")}"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
printf '# Generated by scripts/update-release-build-inputs.sh --write. Review before release.\n# checkout-name canonical-url integration-branch release-commit-sha\n' > "$tmp"
normalize() { printf '%s' "${1%/}" | sed -E 's/\.git$//' | tr '[:upper:]' '[:lower:]'; }
while read -r name url branch sha extra; do
  [[ -z "${name:-}" || "$name" == \#* ]] && continue
  if [[ -n "${extra:-}" || ! "$name" =~ ^[a-z0-9][a-z0-9.-]*$ || ! "$url" =~ ^https?:// || ! "$branch" =~ ^[A-Za-z0-9._/-]+$ ]]; then echo "Invalid release input lock entry: $name $url ${branch:-}" >&2; exit 1; fi
  dir="$parent/$name"
  git -C "$dir" rev-parse --is-inside-work-tree >/dev/null 2>&1 || { echo "Missing sibling Git checkout: $dir" >&2; exit 1; }
  origin="$(git -C "$dir" remote get-url origin 2>/dev/null || true)"
  if [[ -z "$origin" || "$(normalize "$origin")" != "$(normalize "$url")" ]]; then echo "$name origin mismatch: expected $url, found ${origin:-<missing>}" >&2; exit 1; fi
  current_branch="$(git -C "$dir" branch --show-current 2>/dev/null || true)"
  if [[ "$current_branch" != "$branch" ]]; then echo "$name must be checked out on configured release branch $branch (found ${current_branch:-DETACHED})" >&2; exit 1; fi
  git -C "$dir" fetch --prune --no-tags origin
  upstream="$(git -C "$dir" for-each-ref --format='%(upstream:short)' "refs/heads/$branch")"
  [[ "$upstream" == "origin/$branch" ]] || { echo "$name branch $branch must track origin/$branch (found ${upstream:-<missing>})" >&2; exit 1; }
  revision="$(git -C "$dir" rev-parse HEAD)"
  remote_revision="$(git -C "$dir" rev-parse "origin/$branch")"
  [[ "$revision" == "$remote_revision" ]] || { echo "$name is not refreshed to origin/$branch ($revision vs $remote_revision)" >&2; exit 1; }
  printf '%s %s %s %s\n' "$name" "$url" "$branch" "$revision" >> "$tmp"
done < "$lock"
if [[ "$mode" == --write ]]; then mv "$tmp" "$lock"; trap - EXIT; echo "Regenerated $lock. Review and commit it before creating a release tag."; elif ! cmp -s "$tmp" "$lock"; then echo "Release input lock differs from the current sibling checkouts. Run with --write and review the result." >&2; diff -u "$lock" "$tmp" || true; exit 1; else echo "Release input lock matches every sibling checkout."; fi
